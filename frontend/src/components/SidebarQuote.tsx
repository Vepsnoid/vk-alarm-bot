export default function SidebarQuote() {
  const [index, setIndex] = useState(0)
  const [visible, setVisible] = useState(true)

  useEffect(() => {
    let fadeTimer: ReturnType<typeof setTimeout>
    const interval = setInterval(() => {
      setVisible(false)
      fadeTimer = setTimeout(() => {
        setIndex(i => {
          let next = i
          while (next === i) next = Math.floor(Math.random() * QUOTES.length)
          return next
        })
        setVisible(true)
      }, 300)
    }, 10000)
    return () => { clearInterval(interval); clearTimeout(fadeTimer) }
  }, [])

  return (
    <div className='px-4 pt-8 pb-28'>
      <div className='rounded-2xl border border-dashed border-black/10 dark:border-white/10 bg-black/[0.02] dark:bg-white/[0.03] p-4'>
        <div className='flex items-center gap-1.5 text-[10px] uppercase tracking-wider text-slate-400 dark:text-slate-500 font-semibold mb-2'>
          <Quote className='w-3 h-3' />
          Мудрость мониторинга
        </div>
        <p className={'text-xs text-slate-500 dark:text-slate-400 italic leading-relaxed transition-opacity duration-300 ' + (visible ? 'opacity-100' : 'opacity-0')}>
          «{QUOTES[index]}»
        </p>
      </div>
    </div>
  )
}
